import { useEffect, useState } from "react";
import { api } from "../lib/api";
import Chart from "../components/Line";

type Metric = Record<string, any> & { timestamp?: string };
const chartGroups = [
  { title: "CPU utilization", subtitle: "Observed processor utilization over time", keys: ["cpu_percent"], unit: "%" },
  { title: "Memory utilization", subtitle: "Observed memory utilization over time", keys: ["memory_percent"], unit: "%" },
  { title: "Network usage", subtitle: "Network usage metric from the simulator", keys: ["network_usage"], unit: "" },
  { title: "Active workloads", subtitle: "Workload count during the observation window", keys: ["active_workloads"], unit: "" },
  { title: "Compute instances", subtitle: "Allocated simulator capacity over time", keys: ["instances"], unit: "" },
];

export default function Monitoring() {
  const [history, setHistory] = useState<Metric[]>([]);
  const [error, setError] = useState("");

  useEffect(() => {
    api.get("/api/resources/history")
      .then(response => setHistory(Array.isArray(response.data) ? response.data : []))
      .catch(err => { console.error(err); setError("Unable to load historical telemetry."); });

    const ws = new WebSocket((import.meta.env.VITE_WS_URL || "ws://localhost:8000") + "/ws/metrics");
    ws.onmessage = event => {
      try {
        const reading = JSON.parse(event.data) as Metric;
        setHistory(previous => [...previous, reading].slice(-100));
      } catch (err) { console.error("Invalid telemetry message:", err); }
    };
    ws.onerror = err => console.error("Monitoring WebSocket error:", err);
    return () => ws.close();
  }, []);

  return (
    <main>
      <header className="page-head">
        <div>
          <div className="page-eyebrow">Telemetry center</div>
          <h1 className="page-title">Resource Monitoring</h1>
          <p className="page-description">Live and historical resource telemetry from the local monitoring simulator.</p>
        </div>
        <div className="page-actions"><span className="topbar-chip safety"><span className="chip-dot" /> LIVE FEED</span></div>
      </header>
      {error && <div role="alert" className="alert alert-error">{error}</div>}
      <div className="status-strip">
        <div className="status-item"><span className="status-pulse" /> <strong>WebSocket listener active</strong></div>
        <div className="status-item">Visible readings <strong>{history.length}</strong></div>
        <div className="status-item">Window <strong>Latest 100 samples</strong></div>
      </div>
      <div className="monitoring-grid">
        {chartGroups.map(group => (
          <section key={group.title} className="panel panel-pad">
            <div className="panel-header">
              <div><h2 className="panel-title">{group.title}</h2><p className="panel-subtitle">{group.subtitle}</p></div>
              {group.unit && <span className="topbar-chip">{group.unit}</span>}
            </div>
            <Chart data={history} keys={group.keys} />
          </section>
        ))}
      </div>
      <p className="mt-4 text-[10px] leading-5 text-slate-400">Telemetry shown here is generated by the configured monitoring/simulation provider. It should not be interpreted as production cloud-provider measurements.</p>
    </main>
  );
}
